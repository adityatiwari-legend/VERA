"""One-off VERA VPS provisioner (run from the repo root on the dev machine).

Usage:
  VPS_HOST=139.84.163.150 VPS_USER=root VPS_PASS='...' python scratch/vps_provision.py <step>

Steps:
  setup   — apt install docker/git, clone repo to /opt/vera, create volume,
            install the CI/CD deploy pubkey from ~/.ssh/vera_deploy_ed25519.pub
  env     — build /opt/vera/.env from local .env.local (transformed for prod)
  deploy  — kick off deploy/deploy.sh in the background (nohup)
  poll    — tail /opt/vera/deploy.log (returns non-zero until DONE)
  seed    — db:seed + seed:hisaab inside the app container (tolerates failure)
  verify  — health check on localhost + the public domain

Secrets never appear in this file: they are read from local .env.local and the
password comes from the VPS_PASS environment variable at invocation time.
"""
import os
import secrets
import sys
import time

import paramiko

HOST = os.environ["VPS_HOST"]
USER = os.environ.get("VPS_USER", "root")
PASSWORD = os.environ["VPS_PASS"]
DOMAIN = os.environ.get("VERA_DOMAIN", "vera.adityatiwaridev.xyz")
REPO = "https://github.com/adityatiwari-legend/VERA.git"
APP_DIR = "/opt/vera"


def connect() -> paramiko.SSHClient:
    cli = paramiko.SSHClient()
    cli.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    cli.connect(HOST, username=USER, password=PASSWORD, timeout=30, banner_timeout=30)
    return cli


def run(cli: paramiko.SSHClient, cmd: str, timeout: int = 570) -> int:
    """Run a command, streaming output. Returns exit code."""
    print(f"\n$ {cmd}\n", flush=True)
    transport = cli.get_transport()
    chan = transport.open_session()
    chan.settimeout(timeout)
    chan.exec_command(cmd)
    while True:
        if chan.recv_ready():
            sys.stdout.write(chan.recv(4096).decode(errors="replace"))
            sys.stdout.flush()
        if chan.recv_stderr_ready():
            sys.stdout.write(chan.recv_stderr(4096).decode(errors="replace"))
            sys.stdout.flush()
        if chan.exit_status_ready() and not chan.recv_ready() and not chan.recv_stderr_ready():
            break
        time.sleep(0.2)
    code = chan.recv_exit_status()
    print(f"\n[exit {code}]", flush=True)
    return code


def build_env() -> str:
    """Read local .env.local and transform it into the production .env."""
    src = {}
    with open(".env.local", "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                src[k.strip()] = v.strip()

    keep = [
        "GEMINI_API_KEY", "GEMINI_MODEL",
        "HISAAB_ORACLE_KEYPAIR", "HISAAB_FUNDER_KEYPAIR",
        "HISAAB_CONTRACTOR_PUBKEY", "NEXT_PUBLIC_HISAAB_PROGRAM_ID",
        "SOL_INR_RATE", "ROUGHNESS_THRESHOLD", "ETH_INR_RATE",
        "NEXT_PUBLIC_CHAIN_ID", "BLOCKCHAIN_NETWORK", "DEBUG_SQL",
        "MAX_UPLOAD_SIZE_MB", "DEMO_MODE",
    ]
    lines = [
        "# VERA production env — generated by scratch/vps_provision.py. NEVER commit.",
        "# Database/JWT/chain URLs are provided by docker-compose.yml (postgres service).",
        f"NEXT_PUBLIC_APP_URL=https://{DOMAIN}",
        f"JWT_SECRET={secrets.token_hex(24)}",
        "HISAAB_RPC_URL=https://api.devnet.solana.com",
        "STORAGE_PATH=/app/storage",
    ]
    for k in keep:
        if k in src and src[k] != "":
            lines.append(f"{k}={src[k]}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    step = sys.argv[1]
    cli = connect()
    try:
        if step == "setup":
            run(cli, "apt-get update -y && "
                     "DEBIAN_FRONTEND=noninteractive apt-get install -y ca-certificates curl git "
                     "docker.io docker-compose-v2 && systemctl enable --now docker", timeout=560)
            run(cli, f"git clone {REPO} {APP_DIR} 2>/dev/null || true")
            run(cli, f"git -C {APP_DIR} fetch origin main && git -C {APP_DIR} reset --hard origin/main")
            run(cli, "docker volume create hackxxmuj_postgres_data")
            with open(os.path.expanduser("~/.ssh/vera_deploy_ed25519.pub"), "r", encoding="utf-8") as f:
                pubkey = f.read().strip()
            run(cli, "mkdir -p /root/.ssh && chmod 700 /root/.ssh && "
                     f"grep -qxF '{pubkey}' /root/.ssh/authorized_keys 2>/dev/null || "
                     f"echo '{pubkey}' >> /root/.ssh/authorized_keys; "
                     "chmod 600 /root/.ssh/authorized_keys")
            run(cli, "docker --version && docker compose version && git -C /opt/vera log --oneline -1")

        elif step == "env":
            content = build_env()
            sftp = cli.open_sftp()
            with sftp.open(f"{APP_DIR}/.env", "w") as f:
                f.write(content)
            sftp.chmod(f"{APP_DIR}/.env", 0o600)
            sftp.close()
            print(f"/opt/vera/.env written ({len(content)} bytes, values redacted)")

        elif step == "deploy":
            run(cli, f"cd {APP_DIR} && nohup bash deploy/deploy.sh > /opt/vera/deploy.log 2>&1 & echo started")
            run(cli, "sleep 3 && tail -3 /opt/vera/deploy.log || true")

        elif step == "poll":
            rc = run(cli, "tail -n 12 /opt/vera/deploy.log; "
                          "grep -q 'DONE — deployment complete' /opt/vera/deploy.log && exit 0 || "
                          "grep -qE 'ERROR|exited with code|exit code 1' /opt/vera/deploy.log && exit 2 || exit 3",
                     timeout=60)
            sys.exit(rc)

        elif step == "seed":
            # The runtime image is Next.js standalone (no npm) — seeds run in the
            # dedicated tools container (same as deploy.sh's migrate step).
            # First hardhat deploy from account #0 always lands at this address.
            run(cli, f"cd {APP_DIR} && docker compose run --rm "
                     "-e CONTRACT_ADDRESS=0x5FbDB2315678afecb367f032d93F642f64180aa3 "
                     "migrate npm run db:seed || true", timeout=300)
            run(cli, f"cd {APP_DIR} && set -a && . ./.env && set +a && docker compose run --rm "
                     "-e HISAAB_RPC_URL -e HISAAB_CONTRACTOR_PUBKEY -e GEMINI_API_KEY "
                     "migrate npm run seed:hisaab || true", timeout=300)

        elif step == "verify":
            run(cli, "docker compose -f /opt/vera/docker-compose.yml ps")
            run(cli, "curl -sS -m 10 http://127.0.0.1:3000/api/health")
            run(cli, f"curl -sS -o /dev/null -w '%{{http_code}}\\n' -m 15 http://{DOMAIN}")
        else:
            print(f"unknown step: {step}")
            sys.exit(1)
    finally:
        cli.close()


if __name__ == "__main__":
    main()
